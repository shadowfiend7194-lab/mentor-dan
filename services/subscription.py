from database.subscriptions import (
    get_subscription,
    is_pro,
    activate_test_pro,
    expire_pro,
)


# =========================================================
# ПЛАН ПОЛЬЗОВАТЕЛЯ
# =========================================================

def get_user_plan(user_id):
    """
    Возвращает строго одно из состояний:

    free
    pro
    pro_expired

    ВАЖНО:

    Если подписки вообще нет — это FREE.
    Пользователь никогда не считается бывшим PRO
    без существующей записи о подписке.
    """

    subscription = get_subscription(user_id)

    # -----------------------------------------------------
    # НЕТ ПОДПИСКИ
    # -----------------------------------------------------

    if subscription is None:
        return "free"

    # -----------------------------------------------------
    # АКТИВНЫЙ PRO
    # -----------------------------------------------------

    if (
        subscription["plan"] == "pro"
        and subscription["status"] == "active"
        and is_pro(user_id)
    ):
        return "pro"

    # -----------------------------------------------------
    # PRO ЗАКОНЧИЛСЯ
    # -----------------------------------------------------

    if (
        subscription["plan"] == "pro"
        and subscription["status"] == "expired"
    ):
        return "pro_expired"

    # -----------------------------------------------------
    # ЛЮБОЕ НЕИЗВЕСТНОЕ СОСТОЯНИЕ
    # -----------------------------------------------------

    return "free"


# =========================================================
# ПРОВЕРКА PRO
# =========================================================

def user_has_pro(user_id):
    """
    True только при реально активном PRO.
    """

    return is_pro(user_id)


# =========================================================
# ТЕСТОВЫЙ PRO
# =========================================================

def enable_test_pro(
    user_id,
    days=30
):

    return activate_test_pro(
        user_id,
        days=days
    )


# =========================================================
# ТЕСТОВОЕ ОКОНЧАНИЕ PRO
# =========================================================

def disable_test_pro(user_id):

    return expire_pro(
        user_id
    )